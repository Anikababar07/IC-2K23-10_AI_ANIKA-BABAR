# Propositional Logic in Artificial Intelligence

# Define two propositions
p = True
q = False

print("----- PROPOSITIONAL LOGIC -----")

print("\np =", p)
print("q =", q)

# Logical AND
print("\np AND q =", p and q)

# Logical OR
print("p OR q =", p or q)

# Logical NOT
print("NOT p =", not p)
print("NOT q =", not q)

# Logical implication
implication = (not p) or q
print("\np -> q =", implication)